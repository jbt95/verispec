"""`verispec gen-suite`: the whole conformance suite, not just the property test.

The property test is the part of a conformance suite that the contract
determines.  The rest of it is the same in every project:

* the implementation must start in the state the contract starts in,
* a trace of what the implementation did must conform to the contract,
* and - the part that makes a suite worth having - a suite that cannot fail
  is not a suite.

The first two are generated here, so that no project writes them again, and
so that they are written the same way every time.  The third needs a
deliberately broken implementation, which only the project has; the
generated file says where it goes and what it must look like.
"""

from __future__ import annotations

import re

from .model import Spec

__all__ = ["gen_suite"]

#: The seed of the property test.  Fixed, so that a suite which asserts
#: that the test *fails* on a broken implementation is deterministic: a
#: random walk reaches the bug only sometimes.
DEFAULT_SEED = 20260121


def _camel(name: str) -> str:
    """`todo-core` -> `TodoCore`."""
    parts = re.split(r"[^A-Za-z0-9]+", name)
    return "".join(p[:1].upper() + p[1:] for p in parts if p) or "Adapter"


def _slug(spec: Spec) -> str:
    """The file-name stem of the contract: `todo-core`.

    The stem of the *file*, not of the spec's name: the generated file and
    the trace are named after the contract's file, so that a repository
    with eight contracts has eight obviously-paired files.
    """
    from pathlib import Path

    path = getattr(spec, "path", None)
    if path:
        stem = Path(str(path)).stem
        # `todo-core.verispec` -> `todo-core`
        for suffix in (".verispec", ".spec"):
            if stem.endswith(suffix):
                stem = stem[: -len(suffix)]
        cleaned = re.sub(r"[^a-z0-9]+", "-", stem.lower()).strip("-")
        if cleaned:
            return cleaned
    return re.sub(r"[^a-z0-9]+", "-", spec.name.lower()).strip("-")


def _action_signature(spec: Spec) -> list[str]:
    """The actions the contract allows, with their parameters."""
    out = []
    for action in spec.actions:
        params = ", ".join(f"{pn}: {pv.kind}" for pn, pv in action.params.items())
        out.append(f"{action.name}({params})")
    return out


def gen_suite(
    spec: Spec,
    *,
    lang: str = "typescript",
    adapter: str | None = None,
    adapter_class: str | None = None,
    trace_path: str | None = None,
    seed: int = DEFAULT_SEED,
    generated_import: str | None = None,
) -> str:
    """Generate a complete conformance suite for a contract.

    The adapter import is the one thing the project owns: the path to the
    adapter and the name of its class.  Everything else comes from the
    contract.
    """
    if lang not in {"typescript", "javascript"}:
        raise ValueError(
            f"gen-suite writes a TypeScript or JavaScript suite, not {lang!r}"
        )

    slug = _slug(spec)
    cls = adapter_class or _camel(spec.name) + "Adapter"
    import_path = adapter or f"../adapters/{slug}-adapter.js"
    generated = generated_import or f"./generated/{slug}.verispec.gen.js"
    trace = trace_path or f"traces/{slug}.json"

    lines: list[str] = []
    lines.append("/**")
    lines.append(f" * The conformance suite for {spec.name}.")
    lines.append(" *")
    lines.append(" * Generated by `verispec gen-suite`.  The checks that the contract")
    lines.append(" * determines are here; the one that needs a broken implementation")
    lines.append(" * is marked below.")
    lines.append(" */")
    lines.append('import { test } from "node:test";')
    lines.append('import assert from "node:assert/strict";')
    lines.append(
        f'import {{ checkInit, recordTrace, runConformance, writeTrace }} from "{generated}";'
    )
    lines.append(f'import {{ {cls} }} from "{import_path}";')
    lines.append("")
    lines.append("/** The seed of the property test.  Fixed, so that a suite which")
    lines.append(" *  asserts that the test *fails* on a broken implementation is")
    lines.append(" *  deterministic instead of failing one run in six. */")
    lines.append(f"const SEED = {seed};")
    lines.append("")
    lines.append('test("the implementation follows the spec", () => {')
    lines.append(f"  runConformance(() => new {cls}(), {{ seed: SEED }});")
    lines.append("});")
    lines.append("")
    lines.append(
        'test("the implementation starts in the state the contract starts in", () => {'
    )
    lines.append(f"  checkInit(() => new {cls}());")
    lines.append("});")
    lines.append("")
    lines.append("/** The trace of what the implementation did.  The steps are the")
    lines.append(" *  ones the contract allows, and the checker replays them. */")
    lines.append('test("the recorded trace conforms to the spec", () => {')
    lines.append("  // The contract allows these actions:")
    for signature in _action_signature(spec):
        lines.append(f"  //   {signature}")
    lines.append("  const steps: any[] = [")
    lines.append('    // ["the action", { the: "params" }],')
    lines.append("  ];")
    lines.append(f"  const trace = recordTrace(() => new {cls}(), steps);")
    lines.append(f'  writeTrace("{trace}", trace);')
    lines.append("});")
    lines.append("")
    lines.append("/**")
    lines.append(" * The suite must be able to fail.")
    lines.append(" *")
    lines.append(" * A suite that passes against every implementation proves nothing")
    lines.append(" * about the implementation.  Write a second adapter that breaks")
    lines.append(" * one rule of the contract on purpose, and assert that the")
    lines.append(" * property test catches it:")
    lines.append(" *")
    lines.append(" *   assert.throws(")
    lines.append(
        f" *     () => runConformance(() => new Broken{cls}(), {{ seed: SEED }}),"
    )
    lines.append(" *     (error: unknown) => {")
    lines.append(
        " *       const text = `${(error as Error).message}\\n"
        "${String((error as { cause?: unknown }).cause)}`;"
    )
    lines.append(" *       return /effect mismatch|invariant/.test(text);")
    lines.append(" *     },")
    lines.append(" *   );")
    lines.append(" */")
    lines.append("")

    return "\n".join(lines)
