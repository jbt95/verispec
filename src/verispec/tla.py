
def export_tla(spec):
    vars_list=", ".join(spec.vars)
    lines=[]
    lines.append(f"---- MODULE {spec.name.replace('-','_').replace(' ','_')} ----")
    lines.append("(* Generated by VeriSpec from the canonical YAML spec. Run with TLC/Apalache manually; VeriSpec does not run TLC in this MVP. *)")
    lines.append("EXTENDS Integers, Naturals")
    lines.append(f"VARIABLES {vars_list}")
    lines.append(f"vars == <<{vars_list}>>")
    lines.append("")
    lines.append("Init ==")
    init_lines=[]
    from .model import initial_state
    init=initial_state(spec)
    for n,v in spec.vars.items():
        val=init[n]
        if v.kind=="bool": init_lines.append(f"{n} = {'TRUE' if val else 'FALSE'}")
        elif v.kind=="enum": init_lines.append(f'{n} = "{val}"')
        elif v.kind=="str": init_lines.append(f'{n} = "{val}"')
        else: init_lines.append(f"{n} = {val}")
    lines.append("  /\\ " + "\n  /\\ ".join(init_lines) if init_lines else "  TRUE")
    for a in spec.actions:
        lines.append("")
        sig=", ".join(a.params) 
        lines.append(f"{a.name}({sig}) ==" if sig else f"{a.name} ==")
        parts=[]
        for r in a.requires: parts.append(f"({r})")
        for vn in spec.vars:
            if vn in a.effects: parts.append(f"{vn}' = ({a.effects[vn]})")
            else: parts.append(f"UNCHANGED {vn}")
        lines.append("  /\\ " + "\n  /\\ ".join(parts) if parts else "  TRUE")
    lines.append("")
    if spec.actions:
        parts=[]
        for a in spec.actions:
            if a.params:
                ex=" \\/ ".join([f"\\E {pn} \\in {pv.min if pv.min is not None else 0}..{pv.max if pv.max is not None else 100} : {a.name}({pn})" for pn,pv in a.params.items()])
                parts.append(ex)
            else: parts.append(a.name)
        lines.append("Next == " + " \\/ ".join(parts))
    else: lines.append("Next == FALSE")
    lines.append("Spec == Init /\\ [][Next]_vars")
    for inv in spec.invariants:
        lines.append(f"{inv['name']} == ({inv['expr']})")
    if spec.invariants:
        lines.append("Invariants == " + " /\\ ".join(i["name"] for i in spec.invariants))
    lines.append("====")
    return "\n".join(lines)+"\n"
