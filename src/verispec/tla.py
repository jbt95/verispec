"""TLA+ export and (optional) TLC run.

The export states the *design* of the spec as a TLA+ module: the state
variables, the initial state, one action per spec action, the `Next`
relation and the invariants.  Running it through TLC is a deeper check than
BMC, because TLC explores the state space exhaustively (for the bounded
domains the spec uses).

TLC is not bundled: when it is not installed the command says so instead of
pretending to have checked anything.
"""

from __future__ import annotations

import shutil
import subprocess
import tempfile
from pathlib import Path
from typing import Any

from .codegen import to_tla
from .model import Spec, initial_state
from .temporal import tla_fairness_lines, tla_temporal_lines
from .types import MapType, RecordType

__all__ = ["export_tla", "run_tlc"]


def _module_name(name: str) -> str:
    return "".join(c if c.isalnum() or c == "_" else "_" for c in name)


def _tla_value(v: Any) -> str:
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, str):
        return '"' + v.replace('"', '\\"') + '"'
    return str(v)


def _domain_expr(t) -> str:
    """The TLA+ expression for the finite domain of a collection."""
    domain = getattr(t, "domain", None)
    if domain is None:
        return "{}"
    elem = t.key if isinstance(t, MapType) else t.elem
    if elem.kind == "int":
        return f"{domain[0]}..{domain[-1]}"
    return "{" + ", ".join(_tla_value(d) for d in domain) + "}"


def export_tla(spec: Spec) -> str:
    """Render a TLA+ module for a spec."""
    name = _module_name(spec.name)
    lines: list[str] = []
    lines.append(f"---- MODULE {name} ----")
    lines.append("(* Generated by VeriSpec from the canonical YAML spec.")
    lines.append("   Run it with TLC: java -cp tla2tools.jar tlc2.TLC -config <cfg> " + name + ".tla *)")
    lines.append("*)")
    lines.append("EXTENDS Integers, Naturals, Sequences, FiniteSets")
    lines.append("")
    vars_list = ", ".join(spec.vars)
    lines.append(f"VARIABLES {vars_list}")
    lines.append(f"vars == <<{vars_list}>>")
    lines.append("")
    init = initial_state(spec)
    lines.append("Init ==")
    init_lines = []
    for n, v in spec.vars.items():
        init_lines.append(f"{n} = {_init_expr(v, init[n])}")
    lines.append("  /\\ " + "\n  /\\ ".join(init_lines) if init_lines else "  TRUE")
    lines.append("")
    for a in spec.actions:
        tenv = spec.tenv(a)
        sig = ", ".join(a.params)
        lines.append(f"{a.name}({sig}) ==" if sig else f"{a.name} ==")
        parts = []
        for r in a.requires:
            parts.append(f"({to_tla(r, tenv)})")
        for vn, v in spec.vars.items():
            raw = a.effects.get(vn)
            if raw is None:
                parts.append(f"UNCHANGED {vn}")
            elif isinstance(v.type, RecordType):
                for fname, fexpr in raw.items():
                    parts.append(f"{vn}' = [{vn} EXCEPT !.{fname} = {to_tla(fexpr, tenv)}]")
            else:
                parts.append(f"{vn}' = ({to_tla(str(raw), tenv)})")
        lines.append("  /\\ " + "\n  /\\ ".join(parts) if parts else "  TRUE")
    lines.append("")
    if spec.actions:
        parts = []
        for a in spec.actions:
            if a.params:
                # nested quantifiers: \E p1 \in D1 : \E p2 \in D2 : action(p1, p2)
                ex = f"{a.name}({', '.join(a.params)})"
                for pn, pv in reversed(list(a.params.items())):
                    ex = f"\\E {pn} \\in {_param_domain(pv)} : {ex}"
                parts.append(ex)
            else:
                parts.append(a.name)
        lines.append("Next == " + " \\/ ".join(parts))
    else:
        lines.append("Next == FALSE")
    lines.append("")
    fairness = tla_fairness_lines(spec)
    if fairness:
        lines.extend(fairness)
    temporal = tla_temporal_lines(spec)
    if temporal:
        lines.extend(temporal)
    spec_parts = ["Init", "[][Next]_vars"]
    for action_name in spec.fairness.weak:
        spec_parts.append(f"WF_{action_name}")
    for action_name in spec.fairness.strong:
        spec_parts.append(f"SF_{action_name}")
    lines.append("Spec == " + " /\\ ".join(spec_parts))
    lines.append("")
    for inv in spec.invariants:
        lines.append(f"{inv['name']} == ({to_tla(inv['expr'], spec.types)})")
    if spec.invariants:
        lines.append("")
        lines.append("Invariants == " + " /\\ ".join(i["name"] for i in spec.invariants))
    if spec.temporal:
        lines.append("Temporal == " + " /\\ ".join(p.name for p in spec.temporal))
    lines.append("====")
    return "\n".join(lines) + "\n"


def _param_domain(pv) -> str:
    if pv.kind == "int":
        lo = pv.min if pv.min is not None else 0
        hi = pv.max if pv.max is not None else lo + 100
        return f"{lo}..{hi}"
    if pv.kind == "bool":
        return "{TRUE, FALSE}"
    if pv.kind == "enum":
        return "{" + ", ".join(_tla_value(v) for v in pv.values) + "}"
    return '{"", "a", "b"}'


def _init_expr(var, value: Any) -> str:
    t = var.type
    if t.kind == "map":
        base = f"[k \\in {_domain_expr(t)} |-> {_tla_value(_default_of(t.value))}]"
        if not value:
            return base
        updates = ", ".join(f"![{_tla_value(k)}] = {_tla_value(v)}" for k, v in value.items())
        return f"[{base} EXCEPT {updates}]"
    if t.kind == "set":
        if not value:
            return "{}"
        return "{" + ", ".join(_tla_value(v) for v in sorted(value)) + "}"
    if t.kind == "seq":
        return "<<" + ", ".join(_tla_value(v) for v in value) + ">>"
    if t.kind == "record":
        fields = ", ".join(f"{n} |-> {_tla_value(value[n])}" for n, _ in t.fields)
        return f"[{fields}]"
    return _tla_value(value)


def _default_of(t) -> Any:
    from .types import default_value

    return default_value(t)


def run_tlc(spec: Spec, output: str | None = None, timeout: int = 120) -> dict[str, Any]:
    """Run the TLA+ export through TLC, if TLC is available."""
    module = export_tla(spec)
    workdir = Path(tempfile.mkdtemp(prefix="verispec-tlc-"))
    tla_path = workdir / f"{_module_name(spec.name)}.tla"
    tla_path.write_text(module)
    written = output
    if output:
        Path(output).write_text(module)
    java = shutil.which("java")
    tlc_jar = _find_tlc_jar()
    if not java or not tlc_jar:
        return {
            "ok": True,
            "status": "skipped",
            "checked": False,
            "message": (
                "TLC is not available (need java and tla2tools.jar). The TLA+ module was "
                f"written to {written or tla_path}. Install TLA+ and re-run to check it."
            ),
            "module": str(tla_path),
        }
    cmd = [
        java,
        "-cp",
        tlc_jar,
        "tlc2.TLC",
        "-deadlock",
        "-workers",
        "1",
        f"{_module_name(spec.name)}.tla",
    ]
    try:
        proc = subprocess.run(
            cmd, cwd=workdir, capture_output=True, text=True, timeout=timeout
        )
    except (OSError, subprocess.SubprocessError) as e:
        return {
            "ok": False,
            "status": "error",
            "checked": False,
            "message": f"could not run TLC: {e}",
            "module": str(tla_path),
        }
    out = (proc.stdout or "") + (proc.stderr or "")
    ok = proc.returncode == 0
    return {
        "ok": ok,
        "status": "ok" if ok else "violation",
        "checked": True,
        "message": (
            "TLC checked the design and found no violation"
            if ok
            else f"TLC found a violation:\n{out[-4000:]}"
        ),
        "output": out[-8000:],
        "module": str(tla_path),
    }


def _find_tlc_jar() -> str | None:
    for candidate in ("tla2tools.jar", "/usr/local/lib/tla2tools.jar", "/opt/tla/tla2tools.jar"):
        found = shutil.which(candidate) if "/" not in candidate else candidate
        if found and Path(found).exists():
            return found
    return None
