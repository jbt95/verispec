def gen_python(spec: Spec) -> str:
    """Generate a Hypothesis based conformance test for Python adapters."""
    data = spec.to_dict()
    blob = json.dumps(json.dumps(data, indent=2))
    actions = json.dumps(json.dumps(_param_meta(spec), indent=2))
    header = (
        "# Generated by VeriSpec. DO NOT EDIT.\n"
        "# Adapter contract: reset(), apply(action, **params), snapshot() -> dict\n"
        "# The expected behaviour is computed by the VeriSpec runtime, which uses the\n"
        "# same expression AST as the Z3 checker.\n"
    )
    body = '''
import json
import os

from hypothesis import HealthCheck, assume, given, seed as hypothesis_seed, settings, strategies as st

from verispec.expr import eval_python
from verispec.model import apply_action, check_invariants, initial_state, load_spec_data
from verispec.values import state_from_json

SPEC = json.loads(__BLOB__)
ACTIONS = json.loads(__ACTIONS__)
SPEC_OBJ = load_spec_data(SPEC, "<generated by verispec>")

ADAPTER_FACTORY = None


def _factory():
    if ADAPTER_FACTORY is not None:
        return ADAPTER_FACTORY()
    spec_env = os.environ.get("VERISPEC_ADAPTER")
    if spec_env:
        mod, cls = spec_env.rsplit(":", 1)
        import importlib

        return getattr(importlib.import_module(mod), cls)()
    raise RuntimeError("Set ADAPTER_FACTORY or VERISPEC_ADAPTER=module:Class")


def _strategies():
    out = []
    for action in ACTIONS:
        params = {}
        for name, p in action["params"].items():
            if p["kind"] == "bool":
                params[name] = st.booleans()
            elif p["kind"] == "enum":
                params[name] = st.sampled_from(p["values"])
            elif p["kind"] == "str":
                params[name] = st.text(min_size=1, max_size=8)
            else:
                lo = p["min"] if p["min"] is not None else 0
                hi = p["max"] if p["max"] is not None else lo + 20
                params[name] = st.integers(min_value=lo, max_value=hi)
        out.append((action, params))
    return out


def _check_state(state):
    for inv in SPEC_OBJ.invariants:
        assert eval_python(inv["expr"], dict(state), SPEC_OBJ.types), (
            f"invariant {inv['name']} violated: {inv['expr']} in {state}"
        )


@settings(max_examples=60, deadline=None, suppress_health_check=list(HealthCheck))
@given(data=st.data())
def test_verispec_conformance(data):
    adapter = _factory()
    adapter.reset()
    state = state_from_json(SPEC_OBJ.types, adapter.snapshot())
    expected = initial_state(SPEC_OBJ)
    assert state == expected, f"after reset() expected init {expected}, got {state}"
    _check_state(state)
    prev = dict(state)
    strategies = _strategies()
    for step in range(25):
        action, params_strategy = strategies[
            data.draw(st.integers(min_value=0, max_value=len(strategies) - 1), label=f"action_{step}")
        ]
        params = {name: data.draw(s, label=f"{name}_{step}") for name, s in params_strategy.items()}
        env = {**prev, **params}
        tenv = SPEC_OBJ.tenv(SPEC_OBJ.action(action["name"]))
        if not all(eval_python(r, env, tenv) for r in action["requires"]):
            # the action is not enabled in this state: skip it (the same rule the
            # TypeScript and Go generators follow)
            continue
        expected = apply_action(SPEC_OBJ, prev, action["name"], params)
        adapter.apply(action["name"], **params)
        state = state_from_json(SPEC_OBJ.types, adapter.snapshot())
        assert state == expected, (
            f"step {step} action {action['name']} {params}: "
            f"expected effects {expected}, got {state} (prev={prev})"
        )
        _check_state(state)
        prev = dict(state)


def run_verispec_conformance(seed=None, max_examples=60):
    """Run the conformance property test, optionally with a fixed seed.

    A suite that asserts the property test *fails* on a broken implementation
    needs a deterministic walk: a random one reaches the bug only sometimes.
    """
    if seed is None:
        test_verispec_conformance()
        return
    with hypothesis_seed(seed):
        settings(max_examples=max_examples, deadline=None,
                 suppress_health_check=list(HealthCheck))(test_verispec_conformance)()


if __name__ == "__main__":
    run_verispec_conformance()
    print("verispec generated tests: OK")
'''
    return header + body.replace("__BLOB__", blob).replace("__ACTIONS__", actions)


