def _param_meta(spec: Spec) -> list[dict[str, Any]]:
    """Action metadata used by the generators (name, params, preconditions)."""
    out = []
    for a in spec.actions:
        params = {}
        for pn, pv in a.params.items():
            params[pn] = {
                "kind": pv.kind,
                "min": pv.min,
                "max": pv.max,
                "values": pv.values,
                "type": pv.type_str,
            }
        out.append(
            {
                "name": a.name,
                "params": params,
                "requires": list(a.requires),
                "effects": {k: str(v) for k, v in a.effects.items()},
            }
        )
    return out


def _go_literal_value(value: Any) -> str:
    """A Go literal for a JSON-shaped value."""
    if isinstance(value, dict):
        if not value:
            return "map[string]any{}"
        items = ", ".join(f"{_go_literal(k)}: {_go_literal_value(v)}" for k, v in value.items())
        return "map[string]any{" + items + "}"
    if isinstance(value, list):
        if not value:
            return "[]any{}"
        return "[]any{" + ", ".join(_go_literal_value(v) for v in value) + "}"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if value is None:
        return "nil"
    return _go_literal(str(value))


def _init_go(spec: Spec) -> str:
    """The initial state as a Go literal.

    JSON is not valid Go: a map is `map[string]any{...}`, a set is
    `[]any{...}`, and the keys are quoted.
    """
    from .values import state_to_json

    return _go_literal_value(state_to_json(spec.types, initial_state(spec)))


def _init_json(spec: Spec) -> str:
    """The initial state as JSON, in the representation the adapters use.

    A set is a JSON array, a map is an object with stringified keys, and a
    record is an object: the same shape the trace format uses.
    """
    from .values import state_to_json

    return json.dumps(state_to_json(spec.types, initial_state(spec)))


def _js_doc_type(t) -> str:
    """The JSDoc type of a spec type, for the plain JavaScript dialect."""
    if t.kind == "int":
        return "number"
    if t.kind == "bool":
        return "boolean"
    if t.kind in ("str", "enum"):
        return "string"
    if t.kind == "map":
        return f"Record<string, {_js_doc_type(t.value)}>"
    if t.kind in ("set", "seq"):
        return f"Array<{_js_doc_type(t.elem)}>"
    if t.kind == "record":
        return "Object"
    return "*"


def _ts_type(t) -> str:
    if t.kind == "int":
        return "number"
    if t.kind == "bool":
        return "boolean"
    if t.kind in ("str", "enum"):
        return "string"
    if t.kind == "map":
        return f"Record<string, {_ts_type(t.value)}>"
    if t.kind in ("set", "seq"):
        return f"{_ts_type(t.elem)}[]"
    if t.kind == "record":
        return "{ " + "; ".join(f"{n}: {_ts_type(ft)}" for n, ft in t.fields) + " }"
    raise SpecError(f"no TypeScript type for {t.kind}")


