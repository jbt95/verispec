def gen_go(spec: Spec, package: str = "verispec_conformance", adapter: str | None = None) -> str:
    """Generate a Go conformance test for a Go adapter."""
    var_names = set(spec.vars)
    lines: list[str] = []
    lines.append("// Generated by VeriSpec. DO NOT EDIT.")
    lines.append(
        "// Adapter contract: Reset(); Apply(action string, params map[string]any); Snapshot() map[string]any"
    )
    lines.append(f"package {package}")
    lines.append("")
    lines.append("import (")
    lines.append('\t"fmt"')
    lines.append('\t"math/rand"')
    lines.append('\t"reflect"')
    lines.append('\t"sort"')
    lines.append('\t"testing"')
    if adapter:
        path, _, typ = adapter.rpartition(".")
        qualifier = path.rsplit("/", 1)[-1]
        lines.append(f'\t{qualifier} "{path}"')
    lines.append(")")
    lines.append("")
    lines.append(GO_RUNTIME)
    lines.append("")
    lines.append("type veriAdapter interface {")
    lines.append("\tReset()")
    lines.append("\tApply(action string, params map[string]any)")
    lines.append("\tSnapshot() map[string]any")
    lines.append("}")
    lines.append("")
    if adapter:
        path, _, typ = adapter.rpartition(".")
        qualifier = path.rsplit("/", 1)[-1]
        lines.append(
            f"var veriMakeAdapter = func() veriAdapter {{ return &{qualifier}.{typ}{{}} }}"
        )
    else:
        lines.append("var veriMakeAdapter = func() veriAdapter {")
        lines.append('\tpanic("set veriMakeAdapter to your adapter")')
        lines.append("}")
    lines.append("")
    lines.append(f"var veriSpecInit = {_init_go(spec)}")
    lines.append("")
    for a in spec.actions:
        tenv = spec.tenv(a)
        req_ts = [to_go(r, tenv, var_names) for r in a.requires] or ["true"]
        lines.append(
            f"func veriRequires_{a.name}(state map[string]any, params map[string]any) bool {{"
        )
        lines.append(f"\treturn {' && '.join(req_ts)}")
        lines.append("}")
        eff_parts = []
        record_updates = []
        for k, e in a.effects.items():
            var = spec.vars[k]
            if isinstance(var.type, RecordType):
                for fname, fexpr in e.items():
                    record_updates.append((k, fname, to_go(fexpr, tenv, var_names)))
            else:
                eff_parts.append((k, to_go(str(e), tenv, var_names)))
        lines.append(
            f"func veriEffects_{a.name}(state map[string]any, params map[string]any) map[string]any {{"
        )
        lines.append("\tout := map[string]any{}")
        lines.append("\tfor k, v := range state {")
        lines.append("\t\tout[k] = v")
        lines.append("\t}")
        for k, expr in eff_parts:
            lines.append(f'\tout["{k}"] = ({expr})')
        for k, fname, expr in record_updates:
            lines.append("\trec := map[string]any{}")
            lines.append(f'\tfor rk, rv := range out["{k}"].(map[string]any) {{')
            lines.append("\t\trec[rk] = rv")
            lines.append("\t}")
            lines.append(f'\trec["{fname}"] = ({expr})')
            lines.append(f'\tout["{k}"] = rec')
        lines.append("\treturn out")
        lines.append("}")
    lines.append("")
    for inv in spec.invariants:
        lines.append(f"func veriInvariant_{inv['name']}(state map[string]any) bool {{")
        lines.append(f"\treturn {to_go(inv['expr'], spec.types, var_names)}")
        lines.append("}")
    lines.append("")
    lines.append("// veriRunConformance drives the adapter and reports the first mismatch.")
    lines.append("// It returns an error instead of failing the test directly, so that a")
    lines.append("// conformance suite can also assert that a broken adapter IS detected.")
    lines.append("func veriRunConformance() error {")
    lines.append("\trng := rand.New(rand.NewSource(20240101))")
    lines.append("\tfor iter := 0; iter < 200; iter++ {")
    lines.append("\t\tadapter := veriMakeAdapter()")
    lines.append("\t\tadapter.Reset()")
    lines.append("\t\tprev := adapter.Snapshot()")
    lines.append("\t\tif !veriEqual(prev, veriSpecInit) {")
    lines.append('\t\t\treturn fmt.Errorf("init mismatch: got %v want %v", prev, veriSpecInit)')
    lines.append("\t\t}")
    lines.append("\t\tfor step := 0; step < 25; step++ {")
    lines.append("\t\t\taction := veriActions[rng.Intn(len(veriActions))]")
    lines.append("\t\t\tparams := map[string]any{}")
    lines.append("\t\t\tfor name, arb := range action.params {")
    lines.append("\t\t\t\tparams[name] = arb(rng)")
    lines.append("\t\t\t}")
    lines.append("\t\t\tif !action.requires(prev, params) {")
    lines.append("\t\t\t\tcontinue")
    lines.append("\t\t\t}")
    lines.append("\t\t\texpected := action.effects(prev, params)")
    lines.append("\t\t\tadapter.Apply(action.name, params)")
    lines.append("\t\t\tstate := adapter.Snapshot()")
    lines.append("\t\t\tif !veriEqual(state, expected) {")
    lines.append(
        '\t\t\t\treturn fmt.Errorf("step %d action %s: expected %v got %v", step, action.name, expected, state)'
    )
    lines.append("\t\t\t}")
    lines.append("\t\t\tfor _, inv := range veriInvariants {")
    lines.append("\t\t\t\tif !inv.fn(state) {")
    lines.append('\t\t\t\t\treturn fmt.Errorf("invariant %s violated: %v", inv.name, state)')
    lines.append("\t\t\t\t}")
    lines.append("\t\t\t}")
    lines.append("\t\t\tprev = state")
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append("\treturn nil")
    lines.append("}")
    lines.append("")
    lines.append("func TestVeriSpecConformance(t *testing.T) {")
    lines.append("\tif err := veriRunConformance(); err != nil {")
    lines.append("\t\tt.Fatal(err)")
    lines.append("\t}")
    lines.append("}")
    lines.append("")
    # action table
    lines.append("type veriAction struct {")
    lines.append("\tname     string")
    lines.append("\trequires func(map[string]any, map[string]any) bool")
    lines.append("\teffects  func(map[string]any, map[string]any) map[string]any")
    lines.append("\tparams   map[string]func(*rand.Rand) any")
    lines.append("}")
    lines.append("")
    lines.append("var veriActions = []veriAction{")
    for a in spec.actions:
        params = []
        for pn, pv in a.params.items():
            if pv.kind == "bool":
                params.append(f'"{pn}": func(r *rand.Rand) any {{ return r.Intn(2) == 0 }}')
            elif pv.kind == "enum":
                values = ", ".join(json.dumps(v) for v in pv.values)
                params.append(
                    f'"{pn}": func(r *rand.Rand) any {{ return []any{{{values}}}[r.Intn({len(pv.values)})] }}'
                )
            elif pv.kind == "str":
                params.append(
                    f'"{pn}": func(r *rand.Rand) any {{ return fmt.Sprintf("s%d", r.Intn(5)) }}'
                )
            else:
                lo = pv.min if pv.min is not None else 0
                hi = pv.max if pv.max is not None else lo + 20
                params.append(
                    f'"{pn}": func(r *rand.Rand) any {{ return lo + r.Intn(hi-lo+1) }}'.replace(
                        "lo +", f"{lo} +"
                    ).replace("hi-lo+1", f"{hi - lo + 1}")
                )
        lines.append("\t{")
        lines.append(f'\t\tname: "{a.name}",')
        lines.append(f"\t\trequires: veriRequires_{a.name},")
        lines.append(f"\t\teffects: veriEffects_{a.name},")
        lines.append("\t\tparams: map[string]func(*rand.Rand) any{")
        for p in params:
            lines.append(f"\t\t\t{p},")
        lines.append("\t\t},")
        lines.append("\t},")
    lines.append("}")
    lines.append("")
    lines.append("var veriInvariants = []struct {")
    lines.append("\tname string")
    lines.append("\tfn   func(map[string]any) bool")
    lines.append("}{")
    for inv in spec.invariants:
        lines.append(f'\t{{"{inv["name"]}", veriInvariant_{inv["name"]}}},')
    lines.append("}")
    return _gofmt("\n".join(lines) + "\n")


def _gofmt(code: str) -> str:
    """Format Go source with gofmt when it is available."""
    import shutil
    import subprocess

    if not shutil.which("gofmt"):
        return code
    try:
        proc = subprocess.run(["gofmt"], input=code, capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):  # pragma: no cover - environment
        return code
    if proc.returncode == 0 and proc.stdout:
        return proc.stdout
    return code
