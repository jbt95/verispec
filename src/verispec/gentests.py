"""Generate property tests that exercise an adapter against the spec.

The generated test is the language-agnostic part of the "Route B" strategy:
verify the model once, then check that the real implementation conforms.

Three flavours are produced:

* **python**      - uses the VeriSpec runtime, so the semantics are shared
                    with the checker (no duplicated interpreter).
* **typescript**  - standalone: the spec expressions are transpiled to
                    TypeScript and a small runtime preamble is emitted.
* **go**          - standalone, same idea.
"""

from __future__ import annotations

import json
from typing import Any

from .codegen import _go_literal, to_go, to_ts
from .expr import SpecError
from .model import Spec, initial_state
from .types import RecordType

__all__ = ["gen_python", "gen_typescript", "gen_go", "LANGUAGES"]

LANGUAGES = ("python", "typescript", "go", "rust", "c", "java")


