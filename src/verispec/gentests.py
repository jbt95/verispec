TS_RUNTIME = """
// --- VeriSpec runtime (generated) -----------------------------------------
export type VeriValue = any;

export function veriLen(x: any): number {
  return Array.isArray(x) ? x.length : String(x).length;
}

export function veriMapSize(m: any): number {
  return Object.keys(m).length;
}

// The value arguments are typed as `any` on purpose: a generic would infer
// the literal type of the default (`"none"`), and then
// `veriMapGet(m, k, "none") === "pending"` would not compile.
export function veriMapGet(m: any, k: any, def: any): any {
  const key = String(k);
  return Object.prototype.hasOwnProperty.call(m, key) ? m[key] : def;
}

export function veriMapSet(m: any, k: any, v: any, domain: any[]): any {
  const key = String(k);
  if (!domain.map(String).includes(key)) return { ...m };
  return { ...m, [key]: v };
}

function veriSetCanonical(s: any[]): any[] {
  return [...s].sort((a, b) => String(a).localeCompare(String(b)));
}

export function veriSetAdd(s: any[], v: any, domain: any[]): any[] {
  if (!domain.includes(v)) return veriSetCanonical(s);
  return veriSetCanonical(s.includes(v) ? s : [...s, v]);
}

export function veriSetHas(s: any[], v: any): boolean {
  return s.includes(v);
}

export function veriSeqGet(q: any[], i: number, def: any): any {
  return i >= 0 && i < q.length ? q[i] : def;
}

export function veriSeqAppend(q: any[], v: any): any[] {
  return [...q, v];
}

export function veriKeys(m: any): string[] {
  return Object.keys(m);
}

// The coverage events of one run.  A property test that says nothing about
// what it exercised cannot tell you which parts of the contract your suite
// never reaches.
export const VERISPEC_EVENTS: any[] = [];

export function veriEvent(event: any): void {
  VERISPEC_EVENTS.push(event);
}

export function veriCountValues(m: any, v: any): number {
  let n = 0;
  for (const key of Object.keys(m)) {
    if (m[key] === v) n += 1;
  }
  return n;
}

export function veriSameKeys(a: any, b: any): boolean {
  const ka = Object.keys(a).sort();
  const kb = Object.keys(b).sort();
  if (ka.length !== kb.length) return false;
  for (let i = 0; i < ka.length; i += 1) {
    if (ka[i] !== kb[i]) return false;
  }
  return true;
}

export function veriValues(m: any, def: any): any[] {
  return Object.values(m);
}

export function veriContainsKey(m: any, k: any): boolean {
  return Object.prototype.hasOwnProperty.call(m, String(k));
}

export function veriContains(l: any[], v: any): boolean {
  return l.includes(v);
}

export function veriFloorDiv(a: number, b: number): number {
  if (b === 0) throw new Error("division by zero");
  return Math.floor(a / b);
}

export function veriMod(a: number, b: number): number {
  if (b === 0) throw new Error("modulo by zero");
  const r = a % b;
  return r !== 0 && Math.sign(r) !== Math.sign(b) ? r + b : r;
}

export function veriEqual(a: any, b: any): boolean {
  if (a === b) return true;
  if (Array.isArray(a) && Array.isArray(b)) {
    return a.length === b.length && a.every((x, i) => veriEqual(x, b[i]));
  }
  if (a && b && typeof a === "object" && typeof b === "object") {
    const ka = Object.keys(a).sort();
    const kb = Object.keys(b).sort();
    if (ka.length !== kb.length) return false;
    if (!ka.every((k, i) => k === kb[i])) return false;
    return ka.every((k) => veriEqual(a[k], b[k]));
  }
  return false;
}
"""

