def gen_typescript(spec: Spec, adapter_import: str | None = None) -> str:
    """Generate a fast-check based conformance test for TypeScript adapters."""
    return _gen_js_family(spec, adapter_import, javascript=False)


def gen_javascript(spec: Spec, adapter_import: str | None = None) -> str:
    """Generate a fast-check based conformance test for plain JavaScript.

    The same test as the TypeScript one, without the type syntax: the
    expressions are transpiled from the same AST, and the runtime helpers are
    the same, so both dialects check exactly the same contract.
    """
    return _gen_js_family(spec, adapter_import, javascript=True)


def _gen_js_family(spec: Spec, adapter_import: str | None, javascript: bool) -> str:
    """Generate a fast-check based conformance test for TypeScript adapters."""
    var_names = set(spec.vars)
    lines: list[str] = []
    lines.append("// Generated by VeriSpec. DO NOT EDIT.")
    lines.append(
        "// Adapter contract: { reset(): void; apply(action: string, params: Record<string, any>): void; snapshot(): Record<string, any> }"
    )
    lines.append("// The spec expressions are transpiled from the same AST the Z3 checker uses.")
    lines.append("import * as fc from 'fast-check';")
    lines.append("import { writeFileSync } from 'node:fs';")
    if adapter_import:
        lines.append(f"import {{ makeAdapter }} from {adapter_import!r};".replace("'", '"'))
    lines.append(JS_RUNTIME if javascript else TS_RUNTIME)
    lines.append("")
    state_fields = "; ".join(f"{n}: {_ts_type(v.type)}" for n, v in spec.vars.items())
    param_types: dict[str, Any] = {}
    for a in spec.actions:
        for pn, pv in a.params.items():
            param_types.setdefault(pn, pv.type)
    param_fields = {f"{pn}: {_ts_type(t)}" for pn, t in param_types.items()}
    if javascript:
        # plain JavaScript: the types travel as JSDoc, so editors still help
        lines.append("/**")
        lines.append(" * @typedef {Object} SpecState")
        for n, v in spec.vars.items():
            lines.append(f" * @property {{{_js_doc_type(v.type)}}} {n}")
        lines.append(" */")
        if param_fields:
            lines.append("/**")
            lines.append(" * @typedef {Object} SpecParams")
            for pn, pt in sorted(param_types.items()):
                lines.append(f" * @property {{{_js_doc_type(pt)}}} {pn}")
            lines.append(" */")
    else:
        lines.append(f"export interface SpecState {{ {state_fields} }}")
        if param_fields:
            lines.append(f"export interface SpecParams {{ {'; '.join(sorted(param_fields))} }}")
    lines.append("")
    if javascript:
        lines.append("/** @type {SpecState} */")
        lines.append(f"export const SPEC_INIT = {_init_json(spec)};")
    else:
        lines.append(f"export const SPEC_INIT: SpecState = {_init_json(spec)};")
    lines.append("")

    for a in spec.actions:
        tenv = spec.tenv(a)
        req_ts = [to_ts(r, tenv, var_names) for r in a.requires] or ["true"]
        if javascript:
            lines.append(
                f"export const requires_{a.name} = (state, params) => ({' && '.join(req_ts)});"
            )
        else:
            lines.append(
                f"export const requires_{a.name} = (state: any, params: any): boolean => "
                f"({' && '.join(req_ts)});"
            )
        # The guards, one by one: `requires` is their conjunction, and a
        # coverage report wants to know which of them held.
        if javascript:
            guards = ", ".join(
                f"(state, params) => ({to_ts(r, tenv, var_names)})" for r in a.requires
            )
        else:
            guards = ", ".join(
                f"(state: any, params: any): boolean => ({to_ts(r, tenv, var_names)})"
                for r in a.requires
            )
        lines.append(f"export const guards_{a.name} = [{guards}];")
        eff_parts = []
        for k, e in a.effects.items():
            var = spec.vars[k]
            if isinstance(var.type, RecordType):
                for fname, fexpr in e.items():
                    eff_parts.append(f"{fname}: ({to_ts(fexpr, tenv, var_names)})")
            else:
                eff_parts.append(f"{k}: ({to_ts(str(e), tenv, var_names)})")
        if javascript:
            lines.append(
                f"export const effects_{a.name} = (state, params) => "
                f"({{ ...state, {', '.join(eff_parts)} }});"
            )
        else:
            lines.append(
                f"export const effects_{a.name} = (state: any, params: any): any => "
                f"({{ ...state, {', '.join(eff_parts)} }});"
            )
    lines.append("")
    for inv in spec.invariants:
        if javascript:
            lines.append(
                f"export const invariant_{inv['name']} = (state) => "
                f"({to_ts(inv['expr'], spec.types, var_names)});"
            )
        else:
            lines.append(
                f"export const invariant_{inv['name']} = (state: any): boolean => "
                f"({to_ts(inv['expr'], spec.types, var_names)});"
            )
    lines.append("")
    if javascript:
        lines.append("export function checkInvariants(state) {")
    else:
        lines.append("export function checkInvariants(state: any): void {")
    for inv in spec.invariants:
        lines.append(
            f"  if (!invariant_{inv['name']}(state)) "
            f"throw new Error(`invariant {inv['name']} violated: ` + JSON.stringify(state));"
        )
    lines.append("}")
    lines.append("")

    # arbitrary per action with rich parameters
    action_params = "state, params" if javascript else "state: any, params: any"
    lines.append("const ACTIONS = [" if javascript else "const ACTIONS: any[] = [")
    for a in spec.actions:
        tenv = spec.tenv(a)
        req_ts = [to_ts(r, tenv, var_names) for r in a.requires] or ["true"]
        eff_parts = []
        for k, e in a.effects.items():
            var = spec.vars[k]
            if isinstance(var.type, RecordType):
                for fname, fexpr in e.items():
                    eff_parts.append(f"{fname}: ({to_ts(fexpr, tenv, var_names)})")
            else:
                eff_parts.append(f"{k}: ({to_ts(str(e), tenv, var_names)})")
        arbitraries = []
        for pn, pv in a.params.items():
            if pv.kind == "bool":
                arbitraries.append(f"{pn}: fc.boolean()")
            elif pv.kind == "enum":
                arbitraries.append(
                    f"{pn}: fc.constantFrom({', '.join(json.dumps(v) for v in pv.values)})"
                )
            elif pv.kind == "str":
                arbitraries.append(f"{pn}: fc.string()")
            else:
                lo = pv.min if pv.min is not None else 0
                hi = pv.max if pv.max is not None else lo + 20
                arbitraries.append(f"{pn}: fc.integer({{min: {lo}, max: {hi}}})")
        lines.append(
            "  {"
            f"name: {json.dumps(a.name)},"
            f"requires: ({action_params}) => ({' && '.join(req_ts)}),"
            f"effects: ({action_params}) => ({{ ...state, {', '.join(eff_parts)} }}),"
            f"params: fc.record({{ {', '.join(arbitraries)} }}),"
            "},"
        )
    lines.append("];")
    lines.append("")
    any_type = "" if javascript else ": any"
    lines.append(f"const GUARDS{any_type} = {{")
    for a in spec.actions:
        lines.append(f"  {json.dumps(a.name)}: guards_{a.name},")
    lines.append("};")
    lines.append("")
    lines.append(f"const INVARIANT_FNS{any_type} = {{")
    for inv in spec.invariants:
        lines.append(f"  {json.dumps(inv['name'])}: invariant_{inv['name']},")
    lines.append("};")
    lines.append("")
    lines.append(
        "const STEP = fc.oneof(...ACTIONS.map((a) => fc.record({ action: fc.constant(a.name), params: a.params })));"
    )
    lines.append("")
    if javascript:
        lines.append("export function runConformance(makeAdapter, options) {")
    else:
        lines.append(
            "export function runConformance("
            "makeAdapter: () => any,"
            " options?: { seed?: number; numRuns?: number; events?: string },"
            "): void {"
        )
    lines.append("  try {")
    lines.append("  fc.assert(")
    lines.append("    fc.property(fc.array(STEP, { maxLength: 25 }), (steps) => {")
    lines.append("      const adapter = makeAdapter();")
    lines.append("      adapter.reset();")
    lines.append("      let prev = adapter.snapshot();")
    lines.append(
        "      if (!veriEqual(prev, SPEC_INIT)) throw new Error('init mismatch ' + JSON.stringify(prev));"
    )
    lines.append("      checkInvariants(prev);")
    lines.append("      for (const step of steps) {")
    lines.append("        const a = ACTIONS.find((x) => x.name === step.action);")
    lines.append("        const params = step.params;")
    lines.append("        const guards = GUARDS[a.name] || [];")
    lines.append("        for (let gi = 0; gi < guards.length; gi += 1) {")
    lines.append("          veriEvent({ type: \"guard\", action: a.name, index: gi, passed: guards[gi](prev, params) });")
    lines.append("        }")
    lines.append("        if (!a.requires(prev, params)) continue;")
    lines.append("        veriEvent({ type: \"action\", action: a.name, params: params });")
    lines.append("        const expected = a.effects(prev, params);")
    lines.append("        adapter.apply(a.name, params);")
    lines.append("        const state = adapter.snapshot();")
    lines.append("        if (!veriEqual(state, expected))")
    lines.append(
        "          throw new Error(`effect mismatch ${a.name}: expected ${JSON.stringify(expected)} got ${JSON.stringify(state)}`);"
    )
    lines.append("        for (const name of Object.keys(INVARIANT_FNS)) {")
    lines.append("          if (INVARIANT_FNS[name](state)) veriEvent({ type: \"invariant\", name: name });")
    lines.append("        }")
    lines.append("        checkInvariants(state);")
    lines.append("        prev = state;")
    lines.append("      }")
    lines.append("      return true;")
    lines.append("    }),")
    # A suite that asserts the property test *fails* on a broken
    # implementation needs a deterministic walk: a random one reaches the bug
    # only sometimes.  The seed is optional, so the default is unchanged.
    lines.append(
        "    options !== undefined && options.seed !== undefined"
        " ? { seed: options.seed, numRuns: options.numRuns }"
        " : undefined,"
    )
    lines.append("  );")
    lines.append("  } finally {")
    lines.append("    if (options !== undefined && options.events !== undefined) {")
    lines.append("      writeFileSync(options.events, JSON.stringify({ events: VERISPEC_EVENTS }, null, 2) + \"\\n\");")
    lines.append("    }")
    lines.append("  }")
    lines.append("}")
    lines.append("")
    if adapter_import:
        lines.append("runConformance(makeAdapter);")
    return "\n".join(lines) + "\n"


