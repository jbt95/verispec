import json
from .expr import to_ts
from .model import initial_state

def gen_python(spec):
    init=initial_state(spec)
    invs=[(i["name"],i["expr"]) for i in spec.invariants]
    actions=[]
    for a in spec.actions:
        actions.append({"name":a.name,"requires":list(a.requires),"effects":{k:str(v) for k,v in a.effects.items()},
                        "params":{pn:{"min":pv.min,"max":pv.max,"kind":pv.kind,"values":pv.values} for pn,pv in a.params.items()}})
    data={"name":spec.name,"init":init,"invariants":invs,"actions":actions,
          "vars":{n:{"min":v.min,"max":v.max,"kind":v.kind,"values":v.values} for n,v in spec.vars.items()}}
    blob=json.dumps(data,indent=2)
    header="# Generated by VeriSpec. DO NOT EDIT.\n# Adapter: factory()-> reset(), apply(action,**params), snapshot()->dict\n# Preconditions via verispec.expr.eval_python (same AST as Z3).\n"
    body = '''
import os
from hypothesis import given, settings, strategies as st, assume, HealthCheck
from verispec.expr import eval_python
SPEC = __BLOB__
ADAPTER_FACTORY = None
def _factory():
    if ADAPTER_FACTORY is not None:
        return ADAPTER_FACTORY()
    spec_env = os.environ.get("VERISPEC_ADAPTER")
    if spec_env:
        mod, cls = spec_env.rsplit(":", 1)
        import importlib; return getattr(importlib.import_module(mod), cls)()
    raise RuntimeError("Set ADAPTER_FACTORY or VERISPEC_ADAPTER=module:Class")
def check_state(state):
    for name, expr in SPEC["invariants"]:
        assert eval_python(expr, dict(state)), f"invariant {name} violated: {expr} in {state}"
@settings(max_examples=60, deadline=None, suppress_health_check=list(HealthCheck))
@given(data=st.data())
def test_verispec_conformance(data):
    adapter = _factory()
    adapter.reset()
    state = adapter.snapshot()
    assert state == SPEC["init"], f"after reset() expected init {SPEC['init']}, got {state}"
    check_state(state)
    prev = dict(state)
    for step in range(25):
        ai = data.draw(st.integers(min_value=0, max_value=len(SPEC["actions"])-1), label=f"action_idx_{step}")
        action = SPEC["actions"][ai]
        params = {}
        for pn, pv in action["params"].items():
            if pv["kind"] == "bool":
                params[pn] = data.draw(st.booleans(), label=f"{pn}_{step}")
            elif pv["kind"] == "enum":
                params[pn] = data.draw(st.sampled_from(pv["values"]), label=f"{pn}_{step}")
            else:
                lo = pv["min"] if pv["min"] is not None else 0
                hi = pv["max"] if pv["max"] is not None else lo + 20
                params[pn] = data.draw(st.integers(min_value=lo, max_value=hi), label=f"{pn}_{step}")
        env = {**prev, **params}
        assume(all(eval_python(r, env) for r in action["requires"]))
        expected = dict(prev)
        for k, e in action["effects"].items():
            expected[k] = eval_python(e, env)
        adapter.apply(action["name"], **params)
        state = adapter.snapshot()
        assert state == expected, f"step {step} action {action['name']} {params}: expected effects {expected}, got {state} (prev={prev})"
        check_state(state)
        prev = dict(state)
if __name__ == "__main__":
    test_verispec_conformance()
    print("verispec generated tests: OK")
'''
    return header + body.replace("__BLOB__", blob)

def gen_typescript(spec):
    init=initial_state(spec)
    lines=[]
    lines.append(f"// Generated by VeriSpec from spec {spec.name}. DO NOT EDIT.")
    lines.append("// Adapter contract: { reset(): void; apply(action: string, params: Record<string, unknown>): void; snapshot(): Record<string, unknown> }")
    lines.append("// Preconditions/effects transpiled from same spec expressions (AST -> TS) in verispec/expr.py:to_ts. Documented limitation: seed-based skeleton draws no rich params; extend per spec.")
    lines.append("import * as fc from 'fast-check';")
    lines.append(f"export const SPEC_INIT: Record<string, unknown> = {json.dumps(init)};")
    lines.append("export type Adapter = { reset(): void; apply(a: string, p: Record<string, any>): void; snapshot(): Record<string, any> };")
    for a in spec.actions:
        req_ts=[to_ts(r) for r in a.requires] or ["true"]
        lines.append(f"export const requires_{a.name} = (state: any, params: any): boolean => ({' && '.join(req_ts)});")
        eff_entries=", ".join(f"{k}: ({to_ts(str(e))})" for k,e in a.effects.items())
        lines.append(f"export const effects_{a.name} = (state: any, params: any): Record<string, unknown> => ({{ ...state, {eff_entries} }});")
    for inv in spec.invariants:
        lines.append(f"export const invariant_{inv['name']} = (state: any, params: any = {{}}): boolean => ({to_ts(inv['expr'])});")
    lines.append("export function checkInvariants(state: any): void {")
    for inv in spec.invariants:
        lines.append(f"  if (!invariant_{inv['name']}(state)) throw new Error(`invariant {inv['name']} violated: ` + JSON.stringify(state));")
    lines.append("}")
    acts=", ".join(f"{{requires: requires_{a.name}, effects: effects_{a.name}, name: '{a.name}'}}" for a in spec.actions)
    lines.append("export function runConformance(makeAdapter: () => Adapter): void {")
    lines.append(f"  const actions: any[] = [{acts}];")
    lines.append("""  fc.assert(fc.property(fc.array(fc.integer({min:0,max:actions.length-1}), {maxLength:25}), (steps) => {
    const adapter = makeAdapter(); adapter.reset();
    let prev: any = adapter.snapshot();
    if (JSON.stringify(prev) !== JSON.stringify(SPEC_INIT)) throw new Error('init mismatch ' + JSON.stringify(prev));
    checkInvariants(prev);
    for (const idx of steps) {
      const a = actions[idx % actions.length];
      const params: Record<string, any> = {};
      if (!a.requires(prev, params)) continue;
      const expected = a.effects(prev, params);
      adapter.apply(a.name, params);
      const state: any = adapter.snapshot();
      if (JSON.stringify(state) !== JSON.stringify(expected)) throw new Error(`effect mismatch ${a.name}: expected ${JSON.stringify(expected)} got ${JSON.stringify(state)}`);
      checkInvariants(state); prev = state;
    }
    return true;
  }));
}""")
    return "\n".join(lines)+"\n"
