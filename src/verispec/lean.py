"""Lean 4 export.

The export states the spec's invariants as Lean theorems.  It is a **proof
skeleton**, not a proof: the theorems are discharged with ``sorry`` until
somebody proves them (usually with an oracle that turns the Z3 model into a
Lean proof term).

The honest label is ``signature-verified`` for the digest and nothing at all
for the invariants: an unproved ``sorry`` is not a guarantee.
"""

from __future__ import annotations

from .model import Spec
from .types import MapType, RecordType, SeqType, SetType
from .values import value_to_json

__all__ = ["export_lean"]


def _lean_name(name: str) -> str:
    out = "".join(c if c.isalnum() or c == "_" else "_" for c in name)
    if out and out[0].isdigit():
        out = "_" + out
    return out


def _lean_type(t) -> str:
    if t.kind == "int":
        return "Int"
    if t.kind == "bool":
        return "Bool"
    if t.kind in ("str", "enum"):
        return "String"
    if t.kind == "map":
        return f"Std.HashMap String {_lean_type(t.value)}"
    if t.kind == "set":
        return f"Std.HashSet {_lean_type(t.elem)}"
    if t.kind == "seq":
        return f"List {_lean_type(t.elem)}"
    if t.kind == "record":
        return "State"
    return "Int"


def export_lean(spec: Spec) -> str:
    """Render a Lean 4 skeleton for a spec."""
    ns = _lean_name(spec.name)
    lines: list[str] = []
    lines.append("/-")
    lines.append(f"Generated by VeriSpec from {spec.path}.")
    lines.append("")
    lines.append("PROOF SKELETON. The theorems below state the invariants of the spec,")
    lines.append("but they are NOT proved: every `sorry` is an open obligation. VeriSpec")
    lines.append("does not claim these invariants are proved until the `sorry`s are")
    lines.append("replaced by real proofs (usually with an oracle that turns the Z3 model")
    lines.append("into a Lean proof term).")
    lines.append("-/")
    lines.append("")
    lines.append("import Mathlib.Data.Int.Basic")
    lines.append("import Mathlib.Data.HashMap.Basic")
    lines.append("import Mathlib.Data.HashSet.Basic")
    lines.append("")
    lines.append(f"namespace {ns}")
    lines.append("")
    # state structure
    lines.append("structure State where")
    if spec.vars:
        for n, v in spec.vars.items():
            lines.append(f"  {_lean_name(n)} : {_lean_type(v.type)}")
    else:  # pragma: no cover - specs always have vars
        lines.append("  unit : Unit")
    lines.append("deriving DecidableEq, Repr")
    lines.append("")
    # init
    init = _init_value(spec)
    lines.append("def init : State :=")
    if spec.vars:
        fields = ", ".join(f"{_lean_name(n)} := {init[n]}" for n in spec.vars)
        lines.append(f"  ⟨{fields}⟩")
    else:  # pragma: no cover
        lines.append("  ⟨()⟩")
    lines.append("")
    # actions
    for a in spec.actions:
        params = " ".join(f"({_lean_name(p)} : {_lean_type(v.type)})" for p, v in a.params.items())
        lines.append(f"def {_lean_name(a.name)} (s : State) {params} : State :=")
        lines.append("  s")
        lines.append("")
    # invariants
    lines.append("-- Invariants (open obligations)")
    for inv in spec.invariants:
        body = _invariant_statement(spec, inv)
        lines.append(f"theorem {_lean_name(inv['name'])} (s : State) :")
        lines.append(f"    {body} := by")
        lines.append("  sorry")
        lines.append("")
    lines.append("end " + ns)
    return "\n".join(lines) + "\n"


def _init_value(spec: Spec) -> dict[str, str]:
    from .model import initial_state

    state = initial_state(spec)
    out: dict[str, str] = {}
    for n, v in spec.vars.items():
        t = v.type
        value = state[n]
        if t.kind == "int":
            out[n] = str(value)
        elif t.kind == "bool":
            out[n] = "true" if value else "false"
        elif t.kind in ("str", "enum"):
            out[n] = '"' + str(value).replace('"', '\\"') + '"'
        elif t.kind == "map":
            pairs = ", ".join(f'"{k}" => {value_to_json(t, {k: v})[k]}' for k, v in value.items())
            out[n] = "(Std.HashMap.emptyWithCapacity 0).insertMany #[" + pairs + "]"
        elif t.kind == "set":
            items = ", ".join(f'"{v}"' for v in sorted(value))
            out[n] = "(Std.HashSet.emptyWithCapacity 0).insertMany #[" + items + "]"
        elif t.kind == "seq":
            items = ", ".join(str(v) for v in value)
            out[n] = "[" + items + "]"
        else:  # record
            out[n] = "⟨⟩"
    return out


def _invariant_statement(spec: Spec, inv: dict[str, str]) -> str:
    expr = inv["expr"]
    for n, v in spec.vars.items():
        if isinstance(v.type, (MapType, SetType, SeqType, RecordType)):
            return (
                f"-- collection invariant, needs a decision procedure: {expr}\n"
                f"    True"
            )
    return _lean_expr(expr, spec)


def _lean_expr(expr: str, spec: Spec) -> str:
    """Translate a spec expression into Lean syntax."""

    from .expr import parse_expr

    try:
        tree = parse_expr(expr)
    except Exception:
        return expr
    return _lean_node(tree.body, spec)


def _lean_node(node, spec: Spec) -> str:
    import ast

    if isinstance(node, ast.Constant):
        v = node.value
        if v is True:
            return "true"
        if v is False:
            return "false"
        if isinstance(v, str):
            return '"' + v.replace('"', '\\"') + '"'
        return str(v)
    if isinstance(node, ast.Name):
        var = spec.vars.get(node.id)
        if var is not None and not isinstance(
            var.type, (MapType, SetType, SeqType, RecordType)
        ):
            return f"s.{_lean_name(node.id)}"
        return node.id
    if isinstance(node, ast.BoolOp):
        op = " ∧ " if isinstance(node.op, ast.And) else " ∨ "
        return "(" + op.join(_lean_node(v, spec) for v in node.values) + ")"
    if isinstance(node, ast.UnaryOp):
        if isinstance(node.op, ast.Not):
            return f"(¬{_lean_node(node.operand, spec)})"
        if isinstance(node.op, ast.USub):
            return f"(-{_lean_node(node.operand, spec)})"
        return _lean_node(node.operand, spec)
    if isinstance(node, ast.BinOp):
        op = {ast.Add: "+", ast.Sub: "-", ast.Mult: "*", ast.FloorDiv: "/", ast.Mod: "%"}[
            type(node.op)
        ]
        return f"({_lean_node(node.left, spec)} {op} {_lean_node(node.right, spec)})"
    if isinstance(node, ast.Compare):
        parts = []
        left = node.left
        for op, comp in zip(node.ops, node.comparators):
            a = _lean_node(left, spec)
            b = _lean_node(comp, spec)
            sym = {
                ast.Eq: "=",
                ast.NotEq: "≠",
                ast.Lt: "<",
                ast.LtE: "≤",
                ast.Gt: ">",
                ast.GtE: "≥",
            }.get(type(op))
            if sym is None:
                raise ValueError(f"operator {type(op).__name__} has no Lean translation")
            parts.append(f"({a} {sym} {b})")
            left = comp
        return " ∧ ".join(parts)
    if isinstance(node, ast.IfExp):
        return (
            f"(if {_lean_node(node.test, spec)} then {_lean_node(node.body, spec)} "
            f"else {_lean_node(node.orelse, spec)})"
        )
    raise ValueError(f"expression node {type(node).__name__} has no Lean translation")
