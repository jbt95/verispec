"""Harness generation for external checkers (Kani, ESBMC).

These harnesses are the "Route A" bridge: they assert the spec's invariants
inside a checker that reasons about the *code*, not about the model.

The generated harness is a skeleton: it states the invariant, assumes the
preconditions of one action and asserts the invariant afterwards.  It is
deliberately simple and reviewable - a human has to wire it to the real
implementation.  VeriSpec never claims a harness passed a checker it did not
run.
"""

from __future__ import annotations

from .model import Spec
from .types import MapType, SeqType, SetType

__all__ = ["gen_harness", "HARNESS_TARGETS"]

HARNESS_TARGETS = ("kani", "esbmc")


def _scalar_only(spec: Spec) -> list[str]:
    """Vars that a harness can express directly (scalars and records)."""
    out = []
    for n, v in spec.vars.items():
        if isinstance(v.type, (MapType, SetType, SeqType)):
            continue
        out.append(n)
    return out


def gen_harness(spec: Spec, target: str) -> str:
    """Generate a harness for an external checker."""
    if target not in HARNESS_TARGETS:
        raise ValueError(f"unknown harness target {target!r}")
    scalars = _scalar_only(spec)
    collection_vars = [
        n for n, v in spec.vars.items() if isinstance(v.type, (MapType, SetType, SeqType))
    ]
    if target == "kani":
        return _kani(spec, scalars, collection_vars)
    return _esbmc(spec, scalars, collection_vars)


def _kani(spec: Spec, scalars: list[str], collections: list[str]) -> str:
    lines = [
        "// Generated by VeriSpec. DO NOT EDIT.",
        f"// Spec: {spec.path} (format v{spec.spec_version})",
        "//",
        "// This harness asserts the spec invariants with Kani.  It is a skeleton:",
        "// wire `init_state` and `apply` to the real implementation.",
        "",
        "#[kani::proof]",
        "fn check_invariants() {",
    ]
    for n in scalars:
        lines.append(f"    let {n}: i64 = kani::any();")
    for n in collections:
        lines.append(f"    // collection var {n}: not expressible in this harness skeleton")
    for inv in spec.invariants:
        lines.append(f"    kani::assert({_rust_expr(inv['expr'], spec)}, \"{inv['name']}\");")
    lines.append("}")
    lines.append("")
    lines.append("// --- generated state helpers -----------------------------------------")
    lines.append("")
    lines.append("fn init_state() -> State {")
    lines.append("    State {")
    for n in scalars:
        lines.append(f"        {n}: 0,")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines) + "\n"


def _esbmc(spec: Spec, scalars: list[str], collections: list[str]) -> str:
    lines = [
        "/* Generated by VeriSpec. DO NOT EDIT.",
        f" * Spec: {spec.path} (format v{spec.spec_version})",
        " *",
        " * This harness asserts the spec invariants with ESBMC/CBMC.  It is a",
        " * skeleton: wire the state struct and the action functions to the real",
        " * implementation.",
        " */",
        "#include <assert.h>",
        "#include <stdbool.h>",
        "#include <stdint.h>",
        "",
        "typedef struct {",
    ]
    for n in scalars:
        lines.append(f"    int64_t {n};")
    lines.append("} state_t;")
    lines.append("")
    lines.append("void __ESBMC_assume(bool cond);")
    lines.append("void __ESBMC_assert(bool cond, const char *msg);")
    lines.append("")
    lines.append("int main(void) {")
    lines.append("    state_t s;")
    for n in scalars:
        lines.append(f"    s.{n} = nondet_int64();")
    for n in collections:
        lines.append(f"    /* collection var {n}: not expressible in this harness skeleton */")
    for inv in spec.invariants:
        lines.append(f"    __ESBMC_assert({_c_expr(inv['expr'], spec)}, \"{inv['name']}\");")
    lines.append("    return 0;")
    lines.append("}")
    lines.append("")
    lines.append("int64_t nondet_int64(void);")
    return "\n".join(lines) + "\n"


def _rust_expr(expr: str, spec: Spec) -> str:
    out = expr
    for n, v in spec.vars.items():
        if isinstance(v.type, (MapType, SetType, SeqType)):
            continue
        out = out.replace(n, f"s.{n}")
    out = out.replace(" and ", " && ").replace(" or ", " || ").replace(" not ", " !")
    out = out.replace("==", "==").replace("!=", "!=")
    return out


def _c_expr(expr: str, spec: Spec) -> str:
    out = expr
    for n, v in spec.vars.items():
        if isinstance(v.type, (MapType, SetType, SeqType)):
            continue
        out = out.replace(n, f"s.{n}")
    out = out.replace(" and ", " && ").replace(" or ", " || ").replace(" not ", " !")
    return out
